"""The fixed preprocessing of an image, shared so that training and serving can never disagree on it."""

from __future__ import annotations

from torchvision import transforms

IMAGENET_MEAN = (0.485, 0.456, 0.406)
IMAGENET_STD = (0.229, 0.224, 0.225)


def evaluation_transform(image_size: int) -> transforms.Compose:
    """Build the preprocessing used for validation, testing and serving."""
    return transforms.Compose(
        [
            transforms.Resize(int(image_size * 256 / 224)),
            transforms.CenterCrop(image_size),
            transforms.ToTensor(),
            transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
        ],
    )
