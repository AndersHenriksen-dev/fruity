"""Writing the results table and chart from the measurements, so neither is ever edited by hand."""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from fruity.lib.evaluation.selection import ModelResult, within_margin

_BACKGROUND = "#0d1114"
_BORDER = "#3a4656"
_TEXT = "#e4eaf2"
_MUTED = "#a7b3c2"
_ACCENT = "#81a8d6"


def _comparison_table(results: list[ModelResult]) -> list[str]:
    """One row per model, smallest first."""
    rows = [
        "| Model | Learning rate | Training time | Size (MB) | Top-1 | Top-5 | p50 (ms) | p95 (ms) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for result in sorted(results, key=lambda result: result.pytorch.size_mb):
        run = result.pytorch
        rows.append(
            f"| `{result.name}` | {result.learning_rate:g} | {result.fit_seconds / 60:.0f} min | {run.size_mb:.1f} "
            f"| {run.top1:.2%} | {run.top5:.2%} | {run.latency_p50_ms:.0f} | {run.latency_p95_ms:.0f} |",
        )
    return rows


def _runtime_table(result: ModelResult) -> list[str]:
    """The same model in each form it can be deployed in."""
    rows = [
        "| Form | Size (MB) | Top-1 | Top-5 | p50 (ms) | p95 (ms) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, run in (("PyTorch", result.pytorch), ("ONNX", result.onnx), ("Quantized ONNX", result.onnx_quantized)):
        rows.append(
            f"| {name} | {run.size_mb:.1f} | {run.top1:.2%} | {run.top5:.2%} "
            f"| {run.latency_p50_ms:.0f} | {run.latency_p95_ms:.0f} |",
        )
    return rows


def write_results(
    results: list[ModelResult],
    chosen: ModelResult,
    margin: float,
    max_p95_ms: float,
    path: Path,
) -> None:
    """Write the results file.

    Args:
        results: The measured models.
        chosen: The model the rule picked.
        margin: The accuracy margin the rule used, as a fraction.
        max_p95_ms: The latency limit the rule used.
        path: Where to write.
    """
    best = max(result.pytorch.top1 for result in results)
    candidates = ", ".join(f"`{result.name}`" for result in within_margin(results, margin))
    lines = [
        "# Results",
        "",
        "Generated by `fruity compare` from `evals/comparison.json`. Do not edit by hand.",
        "",
        "All accuracy here is on the validation set: 7,575 images held out of the official Food-101 training split.",
        "",
        "## Comparison",
        "",
        *_comparison_table(results),
        "",
        "Latency is one image from file to answer, on one CPU core and one thread, as PyTorch.",
        "",
        "![Accuracy against latency for each model](comparison.png)",
        "",
        "## Choice",
        "",
        f"The best validation top-1 is {best:.2%}. Models within {margin * 100:g} points of it: {candidates}.",
        f"The smallest of these with a p95 at or below {max_p95_ms:.0f} ms is **`{chosen.name}`**, "
        f"with a p95 of {chosen.pytorch.latency_p95_ms:.0f} ms.",
        "",
        "## The chosen model in each form",
        "",
        *_runtime_table(chosen),
        "",
        "## Its worst classes",
        "",
        "| Class | Top-1 |",
        "|---|---:|",
        *[f"| {entry.label.replace('_', ' ')} | {entry.top1:.1%} |" for entry in chosen.worst_classes],
        "",
        "## Limits",
        "",
        "- Each model was trained once, with one seed, so small gaps between models may be noise.",
        "- Latency comes from one core of a desktop CPU, which may be faster than a vCPU in the cloud.",
        "- Latency also moves between runs on a desktop, so treat it as a rough figure.",
        "- The hand-in's 76% used a custom split and 100x100 images, so it cannot be compared with these numbers.",
        "",
    ]
    path.write_bytes("\n".join(lines).encode("utf-8"))


def draw_chart(results: list[ModelResult], chosen: ModelResult, max_p95_ms: float, path: Path) -> None:
    """Draw accuracy against latency, with the chosen model marked."""
    figure, axes = plt.subplots(figsize=(8, 4.5), dpi=200, facecolor=_BACKGROUND)
    axes.set_facecolor(_BACKGROUND)
    axes.axvline(max_p95_ms, color=_BORDER, linewidth=1, linestyle="--")
    axes.annotate(
        "latency limit",
        (max_p95_ms, 0.02),
        xycoords=("data", "axes fraction"),
        xytext=(-6, 0),
        textcoords="offset points",
        color=_MUTED,
        ha="right",
    )
    for result in results:
        is_chosen = result.name == chosen.name
        x, y = result.pytorch.latency_p95_ms, result.pytorch.top1 * 100
        axes.scatter(x, y, s=90, color=_ACCENT if is_chosen else _BACKGROUND, edgecolor=_ACCENT, linewidth=2, zorder=3)
        label = f"{result.name}, {result.pytorch.size_mb:.0f} MB" + (" (chosen)" if is_chosen else "")
        axes.annotate(label, (x, y), xytext=(0, 12), textcoords="offset points", color=_TEXT, ha="center")
    axes.set_xscale("log")
    axes.margins(x=0.2, y=0.2)
    axes.set_xlabel("p95 latency on one CPU core (ms, log scale)", color=_MUTED)
    axes.set_ylabel("Validation top-1 accuracy (%)", color=_MUTED)
    axes.tick_params(colors=_MUTED, which="both")
    axes.grid(color=_BORDER, linewidth=0.5, alpha=0.5)
    for side in ("top", "right"):
        axes.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        axes.spines[side].set_color(_BORDER)
    figure.tight_layout()
    figure.savefig(path, facecolor=_BACKGROUND)
    plt.close(figure)
