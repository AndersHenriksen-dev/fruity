"""Writing the load test's table and chart from the measurements, so neither is ever edited by hand."""

from __future__ import annotations

import statistics
from pathlib import Path
from typing import TYPE_CHECKING

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from fruity.lib.shared.palette import ACCENT, BACKGROUND, BORDER, MUTED, TEXT

if TYPE_CHECKING:
    from fruity.lib.loadtest.run import LoadResults

_CHART_FILE = "load_test.png"


def _stage_table(results: LoadResults) -> list[str]:
    """One row per number of users."""
    rows = [
        "| Users | Requests | Failures | Requests/s | p50 (ms) | p95 (ms) | p99 (ms) | Most replicas |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for stage in results.stages:
        replicas = "not measured" if stage.max_replicas is None else f"{stage.max_replicas:.0f}"
        rows.append(
            f"| {stage.users} | {stage.requests:,} | {stage.failures:,} | {stage.requests_per_second:.1f} "
            f"| {stage.p50_ms:.0f} | {stage.p95_ms:.0f} | {stage.p99_ms:.0f} | {replicas} |",
        )
    return rows


def _soak_lines(results: LoadResults) -> list[str]:
    """Summarize the long steady run, if there was one."""
    soak = results.soak
    if soak is None:
        return []
    replicas = "" if soak.max_replicas is None else f" At most {soak.max_replicas:.0f} replicas ran."
    return [
        "## Steady load",
        "",
        f"{soak.users} users for {soak.seconds / 3600:.1f} hours: {soak.requests:,} requests, "
        f"{soak.failures:,} failures, "
        f"{soak.requests_per_second:.1f} requests per second, p50 {soak.p50_ms:.0f} ms, p95 {soak.p95_ms:.0f} ms, "
        f"p99 {soak.p99_ms:.0f} ms.{replicas}",
        "",
    ]


def _cold_start_lines(results: LoadResults) -> list[str]:
    """Summarize the cold starts, if any were measured."""
    if not results.cold_starts_seconds:
        return []
    seconds = results.cold_starts_seconds
    return [
        "## Cold starts",
        "",
        f"From a service scaled to zero to the first answer, {len(seconds)} times: "
        f"median {statistics.median(seconds):.1f} s, fastest {min(seconds):.1f} s, slowest {max(seconds):.1f} s.",
        "",
    ]


def _draw_chart(results: LoadResults, path: Path) -> None:
    """Draw latency and throughput side by side, because they have different scales."""
    users = [stage.users for stage in results.stages]
    panels = (
        ("p95 latency (ms)", [stage.p95_ms for stage in results.stages]),
        ("Requests per second", [stage.requests_per_second for stage in results.stages]),
    )
    figure, axes = plt.subplots(1, 2, figsize=(10, 4), dpi=200, facecolor=BACKGROUND)
    for axis, (title, values) in zip(axes, panels, strict=True):
        axis.set_facecolor(BACKGROUND)
        axis.plot(users, values, color=ACCENT, linewidth=2, marker="o", markersize=8)
        axis.set_title(title, color=TEXT, loc="left")
        axis.set_xlabel("Users", color=MUTED)
        axis.set_xscale("log", base=2)
        axis.set_xticks(users, labels=[str(count) for count in users])
        axis.minorticks_off()
        axis.set_ylim(bottom=0)
        axis.tick_params(colors=MUTED)
        axis.grid(color=BORDER, linewidth=0.5, alpha=0.5)
        for side in ("top", "right"):
            axis.spines[side].set_visible(False)
        for side in ("left", "bottom"):
            axis.spines[side].set_color(BORDER)
    figure.tight_layout()
    figure.savefig(path, facecolor=BACKGROUND)
    plt.close(figure)


def write_report(results: LoadResults, output: Path) -> None:
    """Write the report and its chart.

    Args:
        results: What was measured.
        output: The folder to write in.
    """
    lines = [
        "# Load test",
        "",
        "Generated by `fruity loadtest` from `load_test.json`. Do not edit by hand.",
        "",
        f"Target: `{results.target}`. Each simulated user sends a food photo, waits 0.5 to 1.5 seconds and repeats.",
        "",
    ]
    if results.stages:
        _draw_chart(results, output / _CHART_FILE)
        lines += [
            "## Under load",
            "",
            *_stage_table(results),
            "",
            "A failure is any answer that is not a success.",
            "",
            f"![Latency and requests per second by number of users]({_CHART_FILE})",
            "",
        ]
    lines += [
        *_soak_lines(results),
        *_cold_start_lines(results),
        "## Limits",
        "",
        "- The load came from one machine, so these times include its network and its own limits.",
        "- This is a small test of a small service. It says nothing about much larger traffic.",
        "",
    ]
    (output / "LOAD.md").write_bytes("\n".join(lines).encode("utf-8"))
