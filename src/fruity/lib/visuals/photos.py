"""One openly licensed photo per dish, from Wikimedia Commons, with a credit for each.

Food-101's own photos belong to their photographers and may only be used for research, so the published graphics use
these instead. Only public domain, CC0 and CC BY photos are taken, and the credits file names every author and licence.
"""

from __future__ import annotations

import html
import json
import re
import time
from pathlib import Path

import requests
from pydantic import BaseModel

from fruity.lib.shared.settings import config_for


class PhotosConfig(BaseModel):
    """Where photos come from, which licences are allowed, and where they go."""

    api_url: str
    user_agent: str
    allowed_licences: list[str]
    min_width: int
    download_width: int
    candidates: int
    request_pause_seconds: float
    photo_dir: Path
    credits_path: Path
    manifest_path: Path
    search_terms: dict[str, str]
    pinned: dict[str, str]


CONFIG = config_for(__name__, PhotosConfig)


class Photo(BaseModel):
    """One photo, and what its licence asks of anyone who shows it."""

    dish: str
    title: str
    author: str
    licence: str
    licence_url: str
    source_url: str
    image_url: str


def licence_allowed(licence: str) -> bool:
    """Say whether a licence lets the graphics crop and combine the photo with a credit alone."""
    name = licence.strip().lower()
    return any(re.match(pattern, name) for pattern in CONFIG.allowed_licences)


def _plain(text: str) -> str:
    """Turn the HTML that Commons gives for an author into plain text."""
    return " ".join(html.unescape(re.sub(r"<[^>]+>", " ", text)).split())


def _photo(dish: str, page: dict[str, object]) -> Photo | None:
    """Read one search result, or None if its licence or size does not fit."""
    info = page["imageinfo"][0]  # type: ignore[index]
    meta = info.get("extmetadata", {})
    licence = meta.get("LicenseShortName", {}).get("value", "")
    if not licence_allowed(licence) or info.get("width", 0) < CONFIG.min_width:
        return None
    return Photo(
        dish=dish,
        title=str(page["title"]),
        author=_plain(meta.get("Artist", {}).get("value", "unknown")) or "unknown",
        licence=licence,
        licence_url=meta.get("LicenseUrl", {}).get("value", ""),
        source_url=info["descriptionurl"],
        image_url=info["thumburl"],
    )


def _query(session: requests.Session, **params: str | int) -> list[dict[str, object]]:
    """Ask the Commons API for files with their licence details, in its own ranking order."""
    base: dict[str, str | int] = {
        "action": "query",
        "format": "json",
        "prop": "imageinfo",
        "iiprop": "url|extmetadata|size",
        "iiurlwidth": CONFIG.download_width,
    }
    answer = session.get(CONFIG.api_url, params={**base, **params}, timeout=60)
    answer.raise_for_status()
    pages = answer.json().get("query", {}).get("pages", {})
    time.sleep(CONFIG.request_pause_seconds)
    return sorted(pages.values(), key=lambda page: page.get("index", 0))


def find_photo(session: requests.Session, dish: str) -> Photo | None:
    """Take the pinned file for a dish, or else the best-ranked search result whose licence allows it."""
    if dish in CONFIG.pinned:
        pages = _query(session, titles=CONFIG.pinned[dish])
    else:
        search = CONFIG.search_terms.get(dish, dish.replace("_", " "))
        pages = _query(
            session,
            generator="search",
            gsrnamespace=6,
            gsrsearch=f"{search} filetype:bitmap",
            gsrlimit=CONFIG.candidates,
        )
    for page in pages:
        photo = _photo(dish, page)
        if photo is not None:
            return photo
    return None


def _credits(photos: list[Photo]) -> str:
    """List every photo with its author and licence, as the licences ask."""
    lines = [
        "# Photo credits",
        "",
        "The graphics use one photo per dish from [Wikimedia Commons](https://commons.wikimedia.org/), each under the "
        "licence named here. They were resized and cropped. Generated by `fruity visuals --fetch`.",
        "",
        "| Dish | Photo | Author | Licence |",
        "|---|---|---|---|",
    ]
    for photo in photos:
        licence = f"[{photo.licence}]({photo.licence_url})" if photo.licence_url else photo.licence
        author = photo.author.replace("|", "/")
        name = photo.title.removeprefix("File:").replace("|", "/")
        lines.append(f"| {photo.dish.replace('_', ' ')} | [{name}]({photo.source_url}) | {author} | {licence} |")
    return "\n".join([*lines, ""])


def fetch(dishes: list[str]) -> list[Photo]:
    """Find and download a photo for each dish, and write the manifest and credits.

    Raises:
        RuntimeError: If a dish has no photo with an allowed licence.
    """
    session = requests.Session()
    session.headers["User-Agent"] = CONFIG.user_agent
    CONFIG.photo_dir.mkdir(parents=True, exist_ok=True)
    photos = []
    for dish in dishes:
        photo = find_photo(session, dish)
        if photo is None:
            raise RuntimeError(f"No openly licensed photo found for {dish}. Add a search term or a pinned file.")
        response = session.get(photo.image_url, timeout=60)
        response.raise_for_status()
        (CONFIG.photo_dir / f"{dish}.jpg").write_bytes(response.content)
        photos.append(photo)
        time.sleep(CONFIG.request_pause_seconds)
    CONFIG.manifest_path.parent.mkdir(parents=True, exist_ok=True)
    payload = [photo.model_dump() for photo in photos]
    CONFIG.manifest_path.write_bytes(json.dumps(payload, indent=1, ensure_ascii=False).encode("utf-8"))
    CONFIG.credits_path.write_bytes(_credits(photos).encode("utf-8"))
    return photos


def load_photos() -> list[Photo]:
    """Read the manifest of photos already fetched."""
    return [Photo.model_validate(entry) for entry in json.loads(CONFIG.manifest_path.read_text(encoding="utf-8"))]
