"""Score the model on openly licensed photos and draw the graphics: a gallery, where it looks, and a map of the dishes.

The photos come from `photos.py`. They are not from Food-101, so they also show how the model does on photos from
outside its dataset.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
from pydantic import BaseModel
from scipy.optimize import linear_sum_assignment
from sklearn.manifold import TSNE
from torchvision import datasets

from fruity.lib.evaluation import compare
from fruity.lib.serving.inference import Prediction, classify, load_classifier
from fruity.lib.shared.palette import ACCENT, BACKGROUND, BORDER, MUTED, TEXT
from fruity.lib.shared.preprocess import prepare_image
from fruity.lib.shared.settings import config_for
from fruity.lib.training.data import split_indices
from fruity.lib.visuals import photos
from fruity.lib.visuals.drawing import fit, font, label, square
from fruity.lib.visuals.model_parts import Network, softmax

_Z_95 = 1.96
_BATCH = 64


class DrawConfig(BaseModel):
    """What the graphics show, and where they go."""

    model_path: Path
    labels_path: Path
    image_size: int
    gallery_every: int
    gallery_columns: int
    occlusion_dishes: list[str]
    occlusion_patch: int
    occlusion_stride: int
    map_columns: int
    map_rows: int
    map_thumb: int
    map_perplexity: float
    features_cache: Path
    results_path: Path
    report_path: Path
    image_dir: Path


CONFIG = config_for(__name__, DrawConfig)


class PhotoResult(BaseModel):
    """What the model said about one photo."""

    dish: str
    predictions: list[Prediction]

    @property
    def right(self) -> bool:
        """Whether the first answer is the dish."""
        return self.predictions[0].label == self.dish

    @property
    def in_top_five(self) -> bool:
        """Whether the dish is among the five answers."""
        return any(prediction.label == self.dish for prediction in self.predictions)


def score_photos(dishes: list[str]) -> list[PhotoResult]:
    """Name the food in each photo with the code the service runs."""
    classifier = load_classifier(CONFIG.model_path, CONFIG.labels_path, CONFIG.image_size, threads=0)
    return [
        PhotoResult(dish=dish, predictions=classify(classifier, Image.open(photos.CONFIG.photo_dir / f"{dish}.jpg"), 5))
        for dish in dishes
    ]


def _margin(share: float, count: int) -> float:
    """How far sampling alone could move a share, in points, at 95% confidence."""
    return _Z_95 * math.sqrt(share * (1 - share) / count) * 100


def write_report(results: list[PhotoResult], path: Path) -> None:
    """Write how the model did on the photos, with the ones it got wrong."""
    count = len(results)
    top1 = sum(result.right for result in results) / count
    top5 = sum(result.in_top_five for result in results) / count
    wrong = [result for result in results if not result.right]
    lines = [
        "# Photos from outside the dataset",
        "",
        "Generated by `fruity visuals` from `evals/real_photos.json`. Do not edit by hand.",
        "",
        f"One openly licensed photo per dish from Wikimedia Commons, {count} in all, named by the model the service "
        "runs. None of them is from Food-101. Credits are in "
        "[docs/images/photos/CREDITS.md](../docs/images/photos/CREDITS.md).",
        "",
        "| Measure | Result |",
        "|---|---:|",
        f"| Top-1 | {top1:.0%} ({sum(result.right for result in results)} of {count}) |",
        f"| Top-5 | {top5:.0%} ({sum(result.in_top_five for result in results)} of {count}) |",
        "",
        f"With one photo per dish, sampling alone could move top-1 by about {_margin(top1, count):.0f} points, so "
        "this is a rough check, not a second test set.",
        "",
        "## The ones it got wrong",
        "",
        "| Dish | Its first answer | Probability |",
        "|---|---|---:|",
        *[
            f"| {label(result.dish)} | {label(result.predictions[0].label)} | {result.predictions[0].probability:.0%} |"
            for result in wrong
        ],
        "",
    ]
    path.write_bytes("\n".join(lines).encode("utf-8"))


def draw_gallery(results: list[PhotoResult], path: Path) -> None:
    """Draw photos with the model's three first answers, a sample of dishes chosen without looking at the results."""
    sample = results[:: CONFIG.gallery_every]
    columns = CONFIG.gallery_columns
    rows = math.ceil(len(sample) / columns)
    photo_size, pad, text_height = 300, 24, 132
    cell_width, cell_height = photo_size + pad, photo_size + text_height + pad
    canvas = Image.new("RGB", (columns * cell_width + pad, rows * cell_height + pad), BACKGROUND)
    draw = ImageDraw.Draw(canvas)
    for index, result in enumerate(sample):
        x = pad + (index % columns) * cell_width
        y = pad + (index // columns) * cell_height
        canvas.paste(square(Image.open(photos.CONFIG.photo_dir / f"{result.dish}.jpg"), photo_size), (x, y))
        draw.rectangle((x, y, x + photo_size - 1, y + photo_size - 1), outline=BORDER)
        draw.text((x, y + photo_size + 10), fit(draw, label(result.dish), photo_size, 22), fill=TEXT, font=font(22))
        for rank, prediction in enumerate(result.predictions[:3]):
            row_y = y + photo_size + 46 + rank * 28
            is_dish = prediction.label == result.dish
            colour = ACCENT if is_dish else MUTED
            bar_width = round(prediction.probability * 110)
            draw.rectangle((x, row_y + 4, x + 110, row_y + 16), fill=BORDER)
            if bar_width:
                draw.rectangle((x, row_y + 4, x + bar_width, row_y + 16), fill=colour)
            text = f"{prediction.probability:.0%} {label(prediction.label)}"
            draw.text(
                (x + 122, row_y),
                fit(draw, text, photo_size - 122, 17),
                fill=TEXT if is_dish else MUTED,
                font=font(17),
            )
    canvas.save(path, quality=88, optimize=True)


def _occlusion_map(network: Network, image: Image.Image, dish_index: int) -> tuple[np.ndarray, float]:
    """Cover each part of the photo in turn and record how much the right dish's log-probability drops.

    The log-probability is used because a model 99% sure barely moves its probability when a patch is covered, while
    its log-probability still shows which patches mattered.
    """
    prepared = prepare_image(image.convert("RGB"), CONFIG.image_size)
    base = float(softmax(network.run(prepared[np.newaxis])[0])[0, dish_index])
    base_log = math.log(max(base, 1e-12))
    patch, stride, size = CONFIG.occlusion_patch, CONFIG.occlusion_stride, CONFIG.image_size
    positions = [
        (top, left) for top in range(0, size - patch + 1, stride) for left in range(0, size - patch + 1, stride)
    ]
    drops = np.zeros((size, size), dtype=np.float32)
    counts = np.zeros((size, size), dtype=np.float32)
    for start in range(0, len(positions), _BATCH):
        chunk = positions[start : start + _BATCH]
        batch = np.repeat(prepared[np.newaxis], len(chunk), axis=0)
        for row, (top, left) in enumerate(chunk):
            batch[row, :, top : top + patch, left : left + patch] = 0.0
        probabilities = softmax(network.run(batch)[0])[:, dish_index]
        for (top, left), probability in zip(chunk, probabilities, strict=True):
            drops[top : top + patch, left : left + patch] += max(
                0.0,
                base_log - math.log(max(float(probability), 1e-12)),
            )
            counts[top : top + patch, left : left + patch] += 1
    heat = drops / np.maximum(counts, 1)
    return heat / max(float(heat.max()), 1e-9), base


def draw_occlusion(network: Network, dishes: list[str], labels: list[str], path: Path) -> None:
    """Draw each photo beside a version that stays bright only where covering the photo hurt the right answer."""
    size, pad, text_height = 300, 24, 44
    canvas = Image.new("RGB", (2 * size + 3 * pad, len(dishes) * (size + text_height + pad) + pad), BACKGROUND)
    draw = ImageDraw.Draw(canvas)
    for row, dish in enumerate(dishes):
        image = Image.open(photos.CONFIG.photo_dir / f"{dish}.jpg")
        heat, base = _occlusion_map(network, image, labels.index(dish))
        y = pad + row * (size + text_height + pad)
        shown = square(image, size)
        heat_image = Image.fromarray((heat * 255).astype(np.uint8)).resize((size, size), Image.Resampling.BILINEAR)
        weight = np.asarray(heat_image, dtype=np.float32)[..., None] / 255
        lit = np.asarray(shown, dtype=np.float32) * (0.2 + 0.8 * weight)
        canvas.paste(shown, (pad, y))
        canvas.paste(Image.fromarray(lit.clip(0, 255).astype(np.uint8)), (2 * pad + size, y))
        draw.text((pad, y + size + 10), f"{label(dish)}: {base:.0%} sure", fill=TEXT, font=font(20))
    canvas.save(path, quality=88, optimize=True)


def validation_features(network: Network) -> tuple[np.ndarray, np.ndarray]:
    """Describe every validation image with the model's features, and keep them, since this takes minutes."""
    path = CONFIG.features_cache
    if path.exists():
        saved = np.load(path)
        return saved["features"], saved["labels"]
    datamodule = compare.load_datamodule()
    raw = datasets.Food101(datamodule.data_dir, split="train")
    _, indices = split_indices(len(raw), datamodule.val_fraction, datamodule.split_seed)
    features: list[np.ndarray] = []
    labels: list[int] = []
    for start in range(0, len(indices), _BATCH):
        pairs = [raw[index] for index in indices[start : start + _BATCH]]
        batch = np.stack([prepare_image(image.convert("RGB"), CONFIG.image_size) for image, _ in pairs])
        features.append(network.run(batch)[1])
        labels.extend(label_index for _, label_index in pairs)
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez(path, features=np.concatenate(features), labels=np.array(labels))
    return np.concatenate(features), np.array(labels)


def place_on_grid(points: np.ndarray, columns: int, rows: int) -> list[tuple[int, int]]:
    """Move 2D points to distinct grid cells while keeping neighbours together.

    Raises:
        ValueError: If there are more points than cells.
    """
    if len(points) > columns * rows:
        raise ValueError(f"{len(points)} points do not fit a {columns} by {rows} grid.")
    span = points.max(axis=0) - points.min(axis=0)
    scaled = (points - points.min(axis=0)) / np.where(span == 0, 1, span) * [columns - 1, rows - 1]
    cells = np.array([(column, row) for row in range(rows) for column in range(columns)], dtype=np.float64)
    cost = ((scaled[:, None, :] - cells[None, :, :]) ** 2).sum(axis=2)
    _, chosen = linear_sum_assignment(cost)
    return [(int(cells[cell][0]), int(cells[cell][1])) for cell in chosen]


def draw_dish_map(features: np.ndarray, labels: np.ndarray, dishes: list[str], path: Path) -> None:
    """Place one photo per dish so that dishes the model sees as alike sit close together."""
    missing = [dish for index, dish in enumerate(dishes) if not np.any(labels == index)]
    if missing:
        raise ValueError(f"No validation images for {', '.join(missing)}, so they cannot be placed on the map.")
    centroids = np.stack([features[labels == index].mean(axis=0) for index in range(len(dishes))])
    centroids /= np.linalg.norm(centroids, axis=1, keepdims=True)
    perplexity = min(CONFIG.map_perplexity, len(dishes) - 1)
    points = TSNE(n_components=2, perplexity=perplexity, metric="cosine", init="pca", random_state=0).fit_transform(
        centroids,
    )
    cells = place_on_grid(points, CONFIG.map_columns, CONFIG.map_rows)
    thumb, gap, text_height = CONFIG.map_thumb, 8, 20
    cell_width, cell_height = thumb + gap, thumb + text_height + gap
    canvas = Image.new("RGB", (CONFIG.map_columns * cell_width + gap, CONFIG.map_rows * cell_height + gap), BACKGROUND)
    draw = ImageDraw.Draw(canvas)
    for dish, (column, row) in zip(dishes, cells, strict=True):
        x, y = gap + column * cell_width, gap + row * cell_height
        canvas.paste(square(Image.open(photos.CONFIG.photo_dir / f"{dish}.jpg"), thumb), (x, y))
        draw.text((x, y + thumb + 3), fit(draw, label(dish), thumb, 13), fill=MUTED, font=font(13))
    canvas.save(path, quality=88, optimize=True)


def main(fetch: bool) -> None:
    """Fetch the photos if asked, then score them and draw every graphic."""
    saved: dict[str, str] = json.loads(CONFIG.labels_path.read_text(encoding="utf-8"))
    labels = [name for _, name in sorted(saved.items(), key=lambda pair: int(pair[0]))]
    if fetch:
        photos.fetch(labels)
    results = score_photos(labels)
    CONFIG.results_path.write_bytes(json.dumps([result.model_dump() for result in results], indent=1).encode("utf-8"))
    write_report(results, CONFIG.report_path)
    CONFIG.image_dir.mkdir(parents=True, exist_ok=True)
    draw_gallery(results, CONFIG.image_dir / "gallery.jpg")
    network = Network(CONFIG.model_path)
    draw_occlusion(network, CONFIG.occlusion_dishes, labels, CONFIG.image_dir / "where_it_looks.jpg")
    features, feature_labels = validation_features(network)
    draw_dish_map(features, feature_labels, labels, CONFIG.image_dir / "dish_map.jpg")
    right = sum(result.right for result in results)
    print(f"{right} of {len(results)} photos right; graphics in {CONFIG.image_dir}", flush=True)
